// An Expo config plugin: plain HTTP only to the hosts named at build time, HTTPS for
// everything else. Android (9+) blocks cleartext by default; Expo's usesCleartextTraffic
// would allow it to every host. A network security config can only list exact hosts (not
// "any private address"), so the hosts come from AGENDA_DEV_HOSTS, e.g. your PC's Wi-Fi
// address. The development build's own Metro connection uses the same hosts.
const fs = require('node:fs');
const path = require('node:path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

/** This device, and the PC as the Android emulator sees it. */
const ALWAYS = ['localhost', '127.0.0.1', '10.0.2.2'];
const HOST = /^(?:[a-z0-9-]+\.)*[a-z0-9-]+$/i;

/** "192.168.1.20, mypc.local" → the list of hosts, validated, without duplicates. */
function parseHosts(value = '') {
  const extra = value
    .split(',')
    .map((host) => host.trim())
    .filter((host) => host !== '');
  for (const host of extra) {
    if (!HOST.test(host)) {
      throw new Error(
        `AGENDA_DEV_HOSTS: "${host}" is not a host name or IP address (no scheme or port)`,
      );
    }
  }
  return [...new Set([...ALWAYS, ...extra])];
}

function networkSecurityConfig(hosts) {
  const domains = hosts
    .map((host) => `    <domain includeSubdomains="false">${host}</domain>`)
    .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-local-cleartext.js: HTTPS everywhere except these hosts. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
  <domain-config cleartextTrafficPermitted="true">
${domains}
  </domain-config>
</network-security-config>
`;
}

function withLocalCleartext(config) {
  const hosts = parseHosts(process.env.AGENDA_DEV_HOSTS);
  config = withDangerousMod(config, [
    'android',
    (mod) => {
      const dir = path.join(mod.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), networkSecurityConfig(hosts));
      return mod;
    },
  ]);
  return withAndroidManifest(config, (mod) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(mod.modResults);
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    // The security config decides; this attribute would allow cleartext everywhere.
    delete application.$['android:usesCleartextTraffic'];
    return mod;
  });
}

module.exports = withLocalCleartext;
module.exports.parseHosts = parseHosts;
module.exports.networkSecurityConfig = networkSecurityConfig;
